#!/usr/bin/env node
/**
 * Renders what an agent receives from Argent's MCP server as markdown: one file
 * per tool, one for the server instructions, and an index (README.md) that also
 * explains how clients pass all of it on to their model.
 *
 * It runs the real pipeline on the current source, not a copy of its logic:
 *
 *   tool files -> createRegistry() -> GET /tools -> toMcpToolList() -> tools/list
 *                                                    SERVER_INSTRUCTIONS -> instructions
 *
 * The markdown shows every string of that payload unchanged: each line of a text
 * is a paragraph, code spans stay code, and characters markdown would hide or
 * reinterpret are escaped. Every schema keyword is listed as `key: JSON value`.
 *
 * Every feature flag is at its default: the flags, ARGENT_* variables and
 * device providers of the machine running the script are ignored.
 *
 * Usage:
 *   npm run render:agent-context
 *       Writes packages/tool-server/agent-context/, which git ignores.
 *   npm run render:agent-context -- --out <dir> [--enable <flag>]...
 *       Writes to <dir>, with the named flags on. --enable needs --out, so the
 *       default folder only ever holds the default render.
 *
 * The script owns its output folder and replaces it on every run, so a removed
 * tool leaves no stale file. It refuses a non-empty folder it did not write.
 */

import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_OUT = path.join(REPO, "packages", "tool-server", "agent-context");

// Marks a folder as this script's output, so a run may replace it.
const OWNER_FILE = ".render-agent-context";

const GENERATED_MARK =
  "<!-- Generated by scripts/render-agent-context.mjs. Do not edit; run the script again. -->";

// What Claude Code does with the payload, as seen in the requests it sent to the
// Anthropic API. Re-check these after a Claude Code update.
const CLAUDE_CODE_SEEN = "Claude Code 2.1.312, requests captured on 2026-10-28";
// Claude Code cuts the description of an always-loaded tool after this many chars.
const CLAUDE_CODE_DESCRIPTION_LIMIT = 4096;
// Tool fields Claude Code does not pass to the model.
const NOT_SENT_BY_CLAUDE_CODE = new Set(["_meta", "annotations"]);

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});

async function main() {
  const options = parseOptions();
  compile();
  const home = isolateFromThisMachine();
  const context = await loadAgentContext(options.enable, home);
  const files = renderFiles(context, options.enable);
  writeFiles(options.out, files);

  process.chdir(REPO);
  fs.rmSync(home, { recursive: true, force: true });
  const shown = path.relative(REPO, options.out);
  console.log(
    `Wrote ${files.size} files to ${shown.startsWith("..") ? options.out : shown}: ` +
      `${context.tools.length} tools, the server instructions and README.md.`
  );
  // The registry keeps timers alive; nothing is left to wait for.
  process.exit(0);
}

// ---------------------------------------------------------------------------
// 1. Options

function parseOptions() {
  const { values } = parseArgs({
    options: {
      out: { type: "string" },
      enable: { type: "string", multiple: true, default: [] },
      help: { type: "boolean", short: "h" },
    },
  });
  if (values.help) {
    console.log("Usage: npm run render:agent-context [-- --out <dir> [--enable <flag>]...]");
    process.exit(0);
  }
  if (values.enable.length > 0 && !values.out) {
    throw new Error(
      "--enable renders a non-default flag state; pass --out <dir> so it does not replace the default render."
    );
  }
  return { out: path.resolve(values.out ?? DEFAULT_OUT), enable: values.enable };
}

// ---------------------------------------------------------------------------
// 2. Compile: workspace packages load from dist/, so stale output would render
// old text. Incremental, so it takes a second or two when little changed.
// argent-mcp's tsconfig has no project references, so the tools-client it imports
// is listed here; otherwise a fresh checkout fails to compile.

function compile() {
  console.log("Compiling tool-server and argent-mcp (tsc --build)...");
  const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
  const projects = ["packages/tool-server", "packages/argent-tools-client", "packages/argent-mcp"];
  execFileSync(process.execPath, [tsc, "--build", ...projects], { cwd: REPO, stdio: "inherit" });
}

// ---------------------------------------------------------------------------
// 3. Isolate: the tool-server reads flags from ~/.argent and <project>/.argent,
// overrides from ARGENT_* variables, and devices from ~/.argent/providers. All
// of that describes this machine, not the code, so point it at an empty home.

function isolateFromThisMachine() {
  for (const name of Object.keys(process.env)) {
    if (name.toUpperCase().startsWith("ARGENT_")) delete process.env[name];
  }
  const home = fs.mkdtempSync(path.join(os.tmpdir(), "argent-agent-context-"));
  process.env.HOME = home;
  process.env.USERPROFILE = home;
  process.env.DO_NOT_TRACK = "1";
  process.env.ARGENT_DISABLE_DEVICE_PROVIDERS = "1";
  // Set, so the tool-server runs with auth on as in production, and quietly.
  process.env.ARGENT_AUTH_TOKEN = randomBytes(16).toString("hex");
  process.chdir(home);
  return home;
}

// ---------------------------------------------------------------------------
// 4. Load: the real registry, the real GET /tools route and the real MCP mapping.

async function loadAgentContext(enable, home) {
  const toolServer = createRequire(path.join(REPO, "packages", "tool-server", "package.json"));
  const { createRegistry } = toolServer("./dist/utils/setup-registry.js");
  const { createHttpApp } = toolServer("./dist/http.js");
  const { FLAG_REGISTRY, isFlagEnabled } = toolServer("@argent/configuration-core");
  const argentMcp = (file) =>
    import(pathToFileURL(path.join(REPO, "packages", "argent-mcp", "dist", file)).href);
  const { toMcpToolList } = await argentMcp("tool-mapping.js");
  const { SERVER_INSTRUCTIONS } = await argentMcp("instructions.js");

  writeFlags(enable, home, FLAG_REGISTRY);

  const registry = createRegistry();
  const served = await getTools(createHttpApp(registry));
  const tools = toMcpToolList(served);

  const listed = new Set(tools.map((t) => t.name));
  const notListed = [];
  for (const id of registry.getSnapshot().tools) {
    if (listed.has(id)) continue;
    const def = registry.getTool(id);
    notListed.push({ name: id, why: whyNotListed(def, isFlagEnabled) });
  }
  for (const entry of served) {
    if (entry.aliasOf) notListed.push({ name: entry.name, why: `former id of ${entry.aliasOf}` });
  }

  return { tools, instructions: SERVER_INSTRUCTIONS, notListed };
}

function writeFlags(enable, home, flagRegistry) {
  if (enable.length === 0) return;
  const known = new Set(flagRegistry.map((f) => f.name));
  const unknown = enable.filter((name) => !known.has(name));
  if (unknown.length > 0) {
    throw new Error(`Unknown flag: ${unknown.join(", ")}. Known flags: ${[...known].join(", ")}.`);
  }
  fs.mkdirSync(path.join(home, ".argent"), { recursive: true });
  fs.writeFileSync(
    path.join(home, ".argent", "flags.json"),
    JSON.stringify({ flags: Object.fromEntries(enable.map((name) => [name, true])) })
  );
}

async function getTools(handle) {
  const server = await new Promise((resolve) => {
    const s = handle.app.listen(0, "127.0.0.1", () => resolve(s));
  });
  try {
    const res = await fetch(`http://127.0.0.1:${server.address().port}/tools`, {
      headers: { authorization: `Bearer ${process.env.ARGENT_AUTH_TOKEN}` },
    });
    if (!res.ok) throw new Error(`GET /tools failed: ${res.status} ${await res.text()}`);
    return (await res.json()).tools;
  } finally {
    server.close();
    handle.dispose();
  }
}

function whyNotListed(def, isFlagEnabled) {
  if (def.featureFlag && !isFlagEnabled(def.featureFlag)) {
    return `feature flag \`${def.featureFlag}\` is off`;
  }
  if (def.hideWhen?.()) return "hidden by its `hideWhen` right now";
  if (def.hideFromMcp) return "`hideFromMcp`: callable over HTTP and the CLI only";
  return "unknown";
}

// ---------------------------------------------------------------------------
// 5. Render

function renderFiles({ tools, instructions, notListed }, enable) {
  const files = new Map();
  for (const tool of tools) files.set(`${tool.name}.md`, renderTool(tool));
  files.set("_instructions.md", renderInstructions(instructions));
  files.set("README.md", renderIndex(tools, instructions, notListed, enable));
  return files;
}

function renderTool(tool) {
  const otherFields = Object.keys(tool).filter(
    (key) => !["name", "description", "inputSchema"].includes(key)
  );
  return lines(
    GENERATED_MARK,
    "",
    `# ${tool.name}`,
    "",
    ...claudeCodeNote(tool),
    "",
    "## Description",
    "",
    markdownText(tool.description),
    "",
    "## Parameters",
    "",
    ...renderSchema(tool.inputSchema),
    ...otherFields.flatMap((key) => ["", `## ${code(key)}`, "", ...renderField(key, tool[key])]),
    ""
  );
}

// How Claude Code passes this tool to its model, from the captured requests.
function claudeCodeNote(tool) {
  const qualified = code(`mcp__argent__${tool.name}`);
  const points = [];
  if (isAlwaysLoaded(tool)) {
    points.push(
      `Always loaded: this whole definition is sent with every request, as ${qualified}.`
    );
    if (tool.description.length > CLAUDE_CODE_DESCRIPTION_LIMIT) {
      points.push(
        `The description has ${n(tool.description.length)} characters. Claude Code keeps the first ${n(CLAUDE_CODE_DESCRIPTION_LIMIT)} and adds ${code("… [truncated]")}, so the model never sees the rest.`
      );
    }
  } else {
    points.push(
      `Deferred: at first the model sees only the name ${qualified}, in a list of tools it can load. It gets this definition once it loads the tool with ToolSearch.`
    );
  }
  const ellipses = JSON.stringify([tool.description, tool.inputSchema]).split("…").length - 1;
  if (ellipses > 0) {
    points.push(`Claude Code turns each ${code("…")} into ${code("...")} (${ellipses} here).`);
  }
  const notSent = Object.keys(tool).filter((key) => NOT_SENT_BY_CLAUDE_CODE.has(key));
  if (notSent.length > 0) {
    const verb = notSent.length > 1 ? "are" : "is";
    points.push(`${notSent.map(code).join(" and ")} ${verb} not sent to the model.`);
  }
  return [
    "> [!NOTE]",
    `> **How this reaches the model in Claude Code** (${CLAUDE_CODE_SEEN}):`,
    ...points.map((point) => `> - ${point}`),
    ">",
    "> Other clients handle it differently: see [README.md](README.md#how-this-reaches-the-model).",
  ];
}

function renderInstructions(instructions) {
  return lines(
    GENERATED_MARK,
    "",
    "# Server instructions",
    "",
    "> [!NOTE]",
    `> **How this reaches the model in Claude Code** (${CLAUDE_CODE_SEEN}):`,
    "> - Sent once, in the server's reply to `initialize`.",
    '> - Claude Code puts the text in a message, under the headings "# MCP Server Instructions" and "## argent", not in the system prompt.',
    ">",
    "> Some clients drop it: see [README.md](README.md#how-this-reaches-the-model).",
    "",
    markdownText(instructions),
    ""
  );
}

// The input schema, one heading per node. Paths: `a.b` is property b of object
// a, `a[]` the items of array a, and `a/anyOf[0]` the first option of a.
function renderSchema(schema) {
  const out = [`Input schema: ${keywordLine(schema)}`];
  if (Object.keys(schema.properties ?? {}).length === 0) out.push("", "No parameters.");
  renderChildren(schema, "", out);
  return out;
}

function renderChildren(node, at, out) {
  const required = new Set(node.required ?? []);
  for (const [name, child] of Object.entries(node.properties ?? {})) {
    renderNode(at ? `${at}.${name}` : name, child, required.has(name), out);
  }
  if (isSchema(node.items)) renderNode(`${at}[]`, node.items, false, out);
  for (const key of ["anyOf", "oneOf", "allOf"]) {
    (node[key] ?? []).forEach((option, i) => renderNode(`${at}/${key}[${i}]`, option, false, out));
  }
}

function renderNode(at, node, required, out) {
  out.push("", `### ${code(at)}${required ? " · required" : ""}`, "");
  const keywords = keywordLine(node);
  if (keywords) out.push(keywords);
  if (typeof node.description === "string") {
    if (keywords) out.push("");
    out.push(markdownText(node.description));
  }
  renderChildren(node, at, out);
}

// Every key of a schema node that renderNode does not show as structure, as
// `key: JSON value`, in the order sent.
function keywordLine(node) {
  return Object.entries(node)
    .filter(([key, value]) => !isStructural(key, value, node))
    .map(([key, value]) => code(`${key}: ${JSON.stringify(value)}`))
    .join(" · ");
}

function isStructural(key, value, node) {
  if (key === "description") return typeof value === "string";
  if (key === "properties") return true;
  if (key === "required") return node.properties !== undefined;
  if (key === "items") return isSchema(value);
  if (key === "anyOf" || key === "oneOf" || key === "allOf") return Array.isArray(value);
  return false;
}

function isSchema(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

// A tool field other than name, description and inputSchema (`_meta`, ...).
function renderField(key, value) {
  const note = NOT_SENT_BY_CLAUDE_CODE.has(key)
    ? ["Claude Code does not send this to the model.", ""]
    : [];
  if (!isSchema(value)) return [...note, code(JSON.stringify(value))];
  return [
    ...note,
    ...Object.entries(value).map(([k, v]) => `- ${code(k)}: ${code(JSON.stringify(v))}`),
  ];
}

