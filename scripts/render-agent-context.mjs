    "  markdown would hide or change are escaped in the file's source.",
    "- Each parameter heading is a path: `a.b` is property `b` of object `a`, `a[]` the items of",
    '  array `a`, and `a/anyOf[0]` the first option of `a`. "required" comes from the parent\'s',
    "  `required` list.",
    "- The code line under a heading lists the node's schema keywords exactly as sent, as",
    "  `key: JSON value`, in the order sent.",
    "- Other fields of the entry, such as `_meta`, follow at the end.",
    "",
