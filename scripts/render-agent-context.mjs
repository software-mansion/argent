function isAlwaysLoaded(tool) {
  return tool._meta?.["anthropic/alwaysLoad"] === true;
}

function sizeOf(tool) {
  return {
    description: tool.description.length,
    schema: JSON.stringify(tool.inputSchema).length,
    total: JSON.stringify({
      name: tool.name,
      description: tool.description,
      inputSchema: tool.inputSchema,
    }).length,
  };
}

// ---------------------------------------------------------------------------
// Markdown that shows a text unchanged

// Each line becomes a paragraph. Code spans stay code; outside them every
// character markdown would hide or reinterpret is escaped. The escaping is
// checked to be reversible, so the file always holds the exact text.
function markdownText(text) {
  return text
    .split("\n")
    .map((line) => {
      const md = escapeLine(line);
      if (unescapeLine(md) !== line) {
        throw new Error(`Rendering changed this line; this is a bug in the script:\n${line}`);
      }
      return md;
    })
    .join("\n\n");
}

// Leading spaces become &nbsp; so they stay visible, and a line cannot turn
// into a code block.
function escapeLine(line) {
  const indent = line.length - line.trimStart().length;
  const body = splitCodeSpans(line.slice(indent))
    .map((part, i) => (part.code ? part.text : escapePlain(part.text, indent === 0 && i === 0)))
    .join("");
  return "&nbsp;".repeat(indent) + body;
}

function unescapeLine(md) {
  const indent = md.match(/^(?:&nbsp;)*/)[0];
  const body = splitCodeSpans(md.slice(indent.length))
    .map((part) =>
      part.code ? part.text : part.text.replace(/\\(.)|&amp;/g, (m, ch) => ch ?? "&")
    )
    .join("");
  return " ".repeat(indent.length / "&nbsp;".length) + body;
}

const ALWAYS_ESCAPED = new Set(["\\", "*", "<", "[", "~", "$"]);

function escapePlain(text, atLineStart) {
  let out = "";
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ALWAYS_ESCAPED.has(ch)) out += `\\${ch}`;
    // An underscore inside a word never starts emphasis.
    else if (ch === "_" && !(isAlnum(text[i - 1]) && isAlnum(text[i + 1]))) out += "\\_";
    else if (ch === "&" && /^&[A-Za-z0-9#]+;/.test(text.slice(i))) out += "&amp;";
    else out += ch;
  }
  // A heading, a quote, a `+` list, or a line of dashes (a rule). `-` and `1.`
  // lists are left to render as lists.
  return atLineStart ? out.replace(/^(#|>|\+(?=\s)|-(?=-*\s*$))/, "\\$1") : out;
}

function isAlnum(ch) {
  return ch !== undefined && /[A-Za-z0-9]/.test(ch);
}

// Splits a line into code spans and plain text, as CommonMark does: a run of N
// backticks opens a span that the next run of exactly N backticks closes.
function splitCodeSpans(line) {
  const parts = [];
  let plainStart = 0;
  let i = 0;
  while (i < line.length) {
    if (line[i] !== "`") {
      i++;
      continue;
    }
    const open = runLength(line, i);
    let close = -1;
    for (let j = i + open; j < line.length;) {
      if (line[j] !== "`") {
        j++;
        continue;
      }
      const run = runLength(line, j);
      if (run === open) {
        close = j;
        break;
      }
      j += run;
    }
    if (close === -1) {
      i += open; // no closing run: the backticks are plain text
      continue;
    }
    if (i > plainStart) parts.push({ code: false, text: line.slice(plainStart, i) });
    parts.push({ code: true, text: line.slice(i, close + open) });
    i = plainStart = close + open;
  }
  if (plainStart < line.length) parts.push({ code: false, text: line.slice(plainStart) });
  return parts;
}

function runLength(line, at) {
  let end = at;
  while (line[end] === "`") end++;
  return end - at;
}

// A code span showing text exactly: its fence is longer than any backtick run
// inside, and a space pads text that starts or ends with a backtick.
function code(text) {
  const longest = Math.max(0, ...(text.match(/`+/g) ?? []).map((run) => run.length));
  const fence = "`".repeat(longest + 1);
  const pad = text.startsWith("`") || text.endsWith("`") ? " " : "";
  return `${fence}${pad}${text}${pad}${fence}`;
}

function n(value) {
  return value.toLocaleString("en-US");
}

// Joins lines, skipping the false/undefined/null entries of optional lines.
function lines(...entries) {
  return entries.filter((e) => e !== false && e !== undefined && e !== null).join("\n");
}

// ---------------------------------------------------------------------------
// 6. Write: replace the whole folder, so a removed tool leaves no stale file.

function writeFiles(outDir, files) {
  const exists = fs.existsSync(outDir);
  if (
    exists &&
    fs.readdirSync(outDir).length > 0 &&
    !fs.existsSync(path.join(outDir, OWNER_FILE))
  ) {
    throw new Error(
      `${outDir} is not empty and was not written by this script; pass another --out.`
    );
  }
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(
    path.join(outDir, OWNER_FILE),
    "Written by scripts/render-agent-context.mjs, which replaces this folder on every run.\n"
  );
  for (const [name, content] of files) fs.writeFileSync(path.join(outDir, name), content);
}
